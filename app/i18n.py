def langue_valide(code: str | None) -> str:
    return code if code in LANGUES else LANGUE_DEFAUT


def langue_session(request) -> str:
    return langue_valide(request.session.get("langue"))


def t(cle: str, langue: str = LANGUE_DEFAUT) -> str:
    langue = langue_valide(langue)
    return TRADUCTIONS.get(langue, {}).get(cle, TRADUCTIONS_UI.get(langue, {}).get(cle, cle))


def langue_html(code: str) -> str:
    return {"fr": "fr", "en": "en", "mg": "mg"}[langue_valide(code)]
